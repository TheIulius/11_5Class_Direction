// ======================================================================
// 3. AI შეფასების ფუნქცია (Gemini Live API + Smart Semantic Engine)
// ======================================================================
export async function evaluateOpenAnswer(
  item: OpenQuestionItem,
  userAnswer: string,
  userApiKey?: string
): Promise<EvaluationResult> {
  const cleanAns = userAnswer.trim();

  if (!cleanAns || cleanAns.length < 5) {
    return {
      score: 0,
      maxScore: item.points,
      status: 'needs_work',
      feedback: 'პასუხი ცარიელია ან მეტისმეტად მოკლეა. გთხოვთ, ჩამოაყალიბოთ სრულფასოვანი პასუხი ქართულად.',
      keyPointsCovered: [],
      missingPoints: item.criteria,
      sampleAnswer: item.sampleAnswer,
      evaluator: 'builtin'
    };
  }

  // 1. თუ მომხმარებელს მითითებული აქვს Gemini API Key, ვიყენებთ Gemini 2.5 Flash / 1.5 Flash-ს
  const activeKey = userApiKey || (typeof localStorage !== 'undefined' ? localStorage.getItem('gemini_api_key_v1') || '' : '');

  if (activeKey) {
    try {
      const prompt = `
შენ ხარ ქართული ენისა და ლიტერატურის მკაცრი, მაგრამ ობიექტური ექსპერტ-პედაგოგი (XI კლასის დონე).
შეაფასე მოსწავლის პასუხი შემდეგ დავალებაზე:

[დავალება]: ${item.question}
[მაქსიმალური ქულა]: ${item.points}
[შეფასების კრიტერიუმები]:
${item.criteria.map(c => '- ' + c).join('\n')}
[სანიმუშო პასუხი]: ${item.sampleAnswer}

[მოსწავლის პასუხი]:
"${cleanAns}"

გააანალიზე პასუხის სიზუსტე, არგუმენტაცია და შინაარსობრივი სისრულე.
დააბრუნე მკაცრად მხოლოდ და მხოლოდ ვალიდური JSON ობიექტი Markdown კოდის ბლოკების გარეშე შემდეგი ფორმატით:
{
  "score": <რიცხვი 0-დან ${item.points}-მდე (შესაძლებელია 0.5 ბიჯი)>,
  "status": "<"correct" თუ ქულა >= 80%, "partial" თუ 40%-80%, "needs_work" თუ < 40%>",
  "feedback": "<მოკლე, ზუსტი და მეგობრული ქართული ახსნა: რა იყო კარგი, რა დააკლდა და როგორ გააუმჯობესოს>",
  "keyPointsCovered": ["<რაც მოსწავლემ სწორად ასახა>"],
  "missingPoints": ["<რაც აკლია ან გასაღრმავებელია>"]
}
`;

      const res = await fetch(
        `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${encodeURIComponent(activeKey)}`,
        {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            contents: [{ parts: [{ text: prompt }] }],
            generationConfig: {
              temperature: 0.2,
              responseMimeType: 'application/json'
            }
          })
        }
      );

      if (res.ok) {
        const data = await res.json();
        const rawJsonText = data?.candidates?.[0]?.content?.parts?.[0]?.text;
        if (rawJsonText) {
          const parsed = JSON.parse(rawJsonText);
          return {
            score: typeof parsed.score === 'number' ? Math.min(item.points, Math.max(0, parsed.score)) : Math.round(item.points * 0.7),
            maxScore: item.points,
            status: parsed.status || (parsed.score >= item.points * 0.8 ? 'correct' : parsed.score >= item.points * 0.4 ? 'partial' : 'needs_work'),
            feedback: parsed.feedback || 'პასუხი შეფასებულია AI ექსპერტის მიერ.',
            keyPointsCovered: Array.isArray(parsed.keyPointsCovered) ? parsed.keyPointsCovered : [],
            missingPoints: Array.isArray(parsed.missingPoints) ? parsed.missingPoints : [],
            sampleAnswer: item.sampleAnswer,
            evaluator: 'gemini'
          };
        }
      }
    } catch (e) {
      console.warn('[AI Evaluator] Gemini API fallback to builtin engine:', e);
    }
  }

  // 2. ჩაშენებული სემანტიკური ძრავა (Offline Semantic Criteria Matcher)
  const lowerAns = cleanAns.toLowerCase();
  const coveredKeywords = item.keywords.filter(k => lowerAns.includes(k.toLowerCase()));
  const keywordRatio = coveredKeywords.length / Math.max(1, item.keywords.length);
  const wordCount = cleanAns.split(/\s+/).filter(Boolean).length;

  let calculatedScore = 0;
  const coveredPoints: string[] = [];
  const missingPoints: string[] = [];

  item.criteria.forEach((crit) => {
    // Check if criteria matches words or if answer covers key parts
    const critWords = crit.toLowerCase().split(/\s+/).filter(w => w.length > 4);
    const matchCount = critWords.filter(w => lowerAns.includes(w.slice(0, -1))).length;
    if (matchCount >= 2 || keywordRatio >= 0.4) {
      coveredPoints.push(crit);
    } else {
      missingPoints.push(crit);
    }
  });

  const criteriaRatio = item.criteria.length > 0 ? coveredPoints.length / item.criteria.length : keywordRatio;
  const combinedRatio = (criteriaRatio * 0.6) + (keywordRatio * 0.4);

  if (combinedRatio >= 0.65 && wordCount >= 10) {
    calculatedScore = item.points;
  } else if (combinedRatio >= 0.35 && wordCount >= 6) {
    calculatedScore = Math.max(1, Math.round(item.points * 0.65 * 2) / 2);
  } else {
    calculatedScore = Math.max(0.5, Math.round(item.points * 0.3 * 2) / 2);
  }

  const status: 'correct' | 'partial' | 'needs_work' =
    calculatedScore >= item.points * 0.85
      ? 'correct'
      : calculatedScore >= item.points * 0.45
      ? 'partial'
      : 'needs_work';

  let feedback = '';
  if (status === 'correct') {
    feedback = `შესანიშნავია! პასუხი სრულად ფარავს შეფასების კრიტერიუმებს და ავლენს ტექსტის ღრმა გააზრებას. (${calculatedScore}/${item.points} ქულა)`;
  } else if (status === 'partial') {
    feedback = `კარგი მცდელობაა, ძირითადი აზრი დაჭერილია, თუმცა რეკომენდებულია მეტი არგუმენტაცია და ტექსტური ციტატებით გამყარება. (${calculatedScore}/${item.points} ქულა)`;
  } else {
    feedback = `პასუხი საჭიროებს არსებით დახვეწას. ყურადღება მიაქციეთ საკვანძო სიტყვებსა და სანიმუშო პასუხის სტრუქტურას. (${calculatedScore}/${item.points} ქულა)`;
  }

  return {
    score: calculatedScore,
    maxScore: item.points,
    status,
    feedback,
    keyPointsCovered: coveredPoints.length > 0 ? coveredPoints : coveredKeywords.slice(0, 3),
    missingPoints: missingPoints.length > 0 ? missingPoints : ['სრული ტექსტობრივი დასაბუთება'],
    sampleAnswer: item.sampleAnswer,
    evaluator: 'builtin'
  };
}
